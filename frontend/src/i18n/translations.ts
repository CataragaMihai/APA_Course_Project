export const translations = { ro, en, ru };
export type Lang = keyof typeof translations;

/** Replaces {name} placeholders. */
export function format(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (m, k: string) => (k in values ? String(values[k]) : m));
}

export const LOCALE: Record<Lang, string> = { ro: "ro-RO", en: "en-US", ru: "ru-RU" };

/** Locale-aware integer: 475.254 (RO) / 475,254 (EN). */
export function num(n: number, lang: Lang): string {
  return n.toLocaleString(LOCALE[lang]);
}

const UNITS = {
  ro: { attempts: ["încercare", "încercări"], steps: ["pas", "pași"] },
  en: { attempts: ["attempt", "attempts"], steps: ["step", "steps"] },
  ru: { attempts: ["попытка", "попытки", "попыток"], steps: ["шаг", "шага", "шагов"] },
};

/** "399 de încercări", "1.712 pași", "475,254 attempts": Romanian adds "de" when the last two digits are 00 or 20-99. */
export function counted(n: number, unit: "attempts" | "steps", lang: Lang): string {
  if (lang === "ru") {
    // Russian: 1 попытка, 2-4 попытки, 5+ попыток (11-14 are always the last form)
    const d = n % 10, m = n % 100;
    const form = m >= 11 && m <= 14 ? 2 : d === 1 ? 0 : d >= 2 && d <= 4 ? 1 : 2;
    return `${num(n, lang)} ${UNITS.ru[unit][form]}`;
  }
  const [one, many] = UNITS[lang][unit] as string[];
  if (n === 1) return `${num(n, lang)} ${one}`;
  const de = lang === "ro" && n >= 20 && (n % 100 === 0 || n % 100 >= 20) ? "de " : "";
  return `${num(n, lang)} ${de}${many}`;
}
